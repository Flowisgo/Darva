// Caption pace gate: every card must be speakable at one steady tempo.
//
//   node scripts/caption-pace.mjs           check, print the table, rewrite narration.md
//   node scripts/caption-pace.mjs --check   check only (no write)
//
// Rules (exit 1 on any violation):
//   rate      words / (on-screen time − 0.42 s of fades) within 2.35–2.55 w/s (141–153 wpm)
//   min       every card on screen ≥ 2.2 s
//   outlast   card leaves ≤ 0.6 s after its speech ends (speech starts when the 0.22 s fade-in ends)
//   air       0.15–0.35 s between one card leaving and the next appearing (across beats too)
//   inside    each card sits inside its beat
//   display   ≤ 2 lines, ≤ 9 words a line, ≤ 96 characters in all
//   copy      no "!", no "seamless", no "revolutionary"
//
// Times are computed exactly as Demo.tsx places them (frame-rounded at 60 fps,
// clamped to the beat), so the table is what the render shows.
import { build } from "esbuild";
import { mkdirSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";
import { pathToFileURL } from "node:url";

const ROOT = resolve(import.meta.dirname, "..");
const FPS = 60;
const FADE_IN = 0.22;
const FADE_OUT = 0.2;
const RATE = [2.35, 2.55];
const NOMINAL = 2.45;
const AIR = [0.15, 0.35];
const MIN_ON = 2.2;
const MAX_OUTLAST = 0.6;
const EPS = 1e-6;

mkdirSync(join(ROOT, ".cache"), { recursive: true });
const out = join(ROOT, ".cache", "timeline-pace.mjs");
await build({ entryPoints: [join(ROOT, "src/timeline.ts")], bundle: true, platform: "node", format: "esm", outfile: out, logLevel: "error", external: ["remotion", "@remotion/*", "react"] });
const { BEATS } = await import(pathToFileURL(out).href);

const fr = (s) => Math.round(s * FPS);
/** Spoken words: whitespace tokens that contain a letter or digit ("600", "540.00", "Ayşe's"). */
export const words = (s) => s.split(/\s+/).filter((t) => /[\p{L}\p{N}]/u.test(t)).length;

// Place every card on the film's clock, exactly as Demo.tsx does.
const cards = [];
let f = 0;
for (const b of BEATS) {
  const start = f;
  const dur = b.card ? fr(b.cardSeconds ?? 4) : b.segs.reduce((n, s) => n + Math.max(1, fr((s.to - s.from) / s.speed)), 0);
  for (const c of b.captions) {
    const a = start + fr(c.at);
    const z = Math.min(start + dur, start + fr(c.to));
    cards.push({ beat: b.id, beatIn: start / FPS, beatOut: (start + dur) / FPS, from: a / FPS, to: z / FPS, rawTo: (start + fr(c.to)) / FPS, lines: c.lines, cue: c.cue ?? "" });
  }
  f += dur;
}
const total = f / FPS;

let bad = 0;
const rows = cards.map((c, i) => {
  const text = c.lines.join(" ");
  const w = words(text);
  const on = c.to - c.from;
  const speakable = on - FADE_IN - FADE_OUT;
  const rate = w / speakable;
  const speech = w / NOMINAL;
  const outlast = c.to - (c.from + FADE_IN + speech);
  const next = cards[i + 1];
  const air = next ? next.from - c.to : null;
  const why = [];
  if (rate < RATE[0] - EPS) why.push(`slow ${(rate * 60).toFixed(0)} wpm`);
  if (rate > RATE[1] + EPS) why.push(`fast ${(rate * 60).toFixed(0)} wpm`);
  if (on < MIN_ON - EPS) why.push(`on ${on.toFixed(2)} < ${MIN_ON} s`);
  if (outlast > MAX_OUTLAST + EPS) why.push(`outlasts speech by ${outlast.toFixed(2)} s`);
  if (air !== null && (air < AIR[0] - EPS || air > AIR[1] + EPS)) why.push(`air ${air.toFixed(2)} s`);
  if (c.from < c.beatIn - EPS || c.rawTo > c.beatOut + EPS) why.push("outside its beat");
  if (c.lines.length > 2) why.push(`${c.lines.length} lines`);
  for (const l of c.lines) if (words(l) > 9) why.push(`line of ${words(l)} words`);
  if (text.length > 96) why.push(`${text.length} chars`);
  if (/!|seamless|revolutionary/i.test(text)) why.push("banned copy");
  if (why.length) bad++;
  return { n: i + 1, beat: c.beat, from: c.from, to: c.to, on, w, wpm: rate * 60, speech, air, outlast, text, cue: c.cue, why };
});

const p = (s, n) => String(s).padEnd(n);
const q = (s, n) => String(s).padStart(n);
console.log(`${q("#", 2)}  ${p("beat", 14)} ${p("window", 13)} ${q("on", 5)} ${q("words", 5)} ${q("wpm", 4)} ${q("speech", 6)} ${q("air", 5)}  status`);
for (const r of rows)
  console.log(
    `${q(r.n, 2)}  ${p(r.beat, 14)} ${p(`${r.from.toFixed(2)}–${r.to.toFixed(2)}`, 13)} ${q(r.on.toFixed(2), 5)} ${q(r.w, 5)} ${q(r.wpm.toFixed(0), 4)} ${q(r.speech.toFixed(2), 6)} ${q(r.air === null ? "end" : r.air.toFixed(2), 5)}  ${r.why.length ? "FAIL " + r.why.join("; ") : "ok"}`,
  );
const allW = rows.reduce((n, r) => n + r.w, 0);
const wpms = rows.map((r) => r.wpm);
console.log(`${rows.length} cards, ${allW} words, ${Math.min(...wpms).toFixed(0)}–${Math.max(...wpms).toFixed(0)} wpm, film ${total.toFixed(2)} s`);

if (!process.argv.includes("--check")) {
  // narration.md is generated from the same array as the captions: same words, same times.
  const md = [
    "# Narration: Darva, 60 seconds",
    "",
    "<!-- Generated by `npm run pace` from the captions in src/timeline.ts. Do not edit by hand: change the captions and rerun. -->",
    "",
    "The voice-over is the burned-in captions, word for word. Read each card as it appears, at one steady pace (about 150 words a minute), and stop when it fades; the gap before the next card is your breath. No music, dry delivery.",
    "",
    'Say "Ayşe" as **EYE-sheh**. Say "USDC" as letters. Digits are read naturally: "1,500" is "fifteen hundred", "540.00" is "five hundred forty", "645.00" is "six forty-five".',
    "",
    "| Time | Say | Cue |",
    "|---|---|---|",
    ...rows.map((r) => `| ${r.from.toFixed(2)}–${r.to.toFixed(2)} | ${r.text} | ${r.cue} |`),
    "",
    `${rows.length} cards, ${allW} words, ${total.toFixed(1)} s. \`npm run pace\` checks every card's pace and rewrites this file; \`npm run render\` runs it first and stops if a card is too fast, too slow or too short.`,
    "",
    "## Live delivery notes",
    "",
    "- To record the narrated master: read this table over the silent master in one take (48 kHz WAV, starting at 0.0 s), save it as `assets/audio/narration.wav`, and run `npm run render:narrated`.",
    '- If asked "is this real?": every click is the real app and every signature is a real Varial approval on Stellar Testnet; the hashes are in [verification.md](verification.md) and the contract ID is on the end card.',
    "- The buy-out beat is a second rug (No. 0005) on a 1-month loan; in this demo 1 month lasts 1 minute. The chip on screen says so. Mention it only if someone asks.",
    "",
  ].join("\n");
  writeFileSync(join(ROOT, "narration.md"), md);
  console.log("wrote narration.md");
}
if (bad) {
  console.error(`${bad} card(s) fail the pace rules`);
  process.exit(1);
}
